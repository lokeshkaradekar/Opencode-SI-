    public TermuxBackend(Context context, SecureStore secrets) {
        this.ctx = context.getApplicationContext();
        this.secrets = secrets;
        this.cfg = ctx.getSharedPreferences("opencode_si_backend", Context.MODE_PRIVATE);
    }

    // ------------------------------------------------------------------ configuration
    public int port() {
        return cfg.getInt("port", DEFAULT_PORT);
    }

    /** Sets the daemon port and, optionally, a token copied from a manually started daemon. */
    public void configure(int port, String token) throws NativeBridge.BridgeException {
        if (port < 1024 || port > 65535) {
            throw new NativeBridge.BridgeException("INVALID_ARGUMENT", "The port must be between 1024 and 65535.", null);
        }
        cfg.edit().putInt("port", port).commit();
        if (token != null && token.length() > 0) {
            if (token.length() < 24 || token.length() > 200 || !token.matches("^[A-Za-z0-9._~-]+$")) {
                throw new NativeBridge.BridgeException("INVALID_ARGUMENT", "That does not look like a daemon token.", null);
            }
            try {
                secrets.put(TOKEN_ID, token);
            } catch (SecureStore.SecureStoreException e) {
                throw new NativeBridge.BridgeException(e.code, e.getMessage(), null);
            }
        }
        sessions.clear();
        running.clear();
    }

    private String token() throws NativeBridge.BridgeException {
        try {
            return secrets.getOrCreateRandom(TOKEN_ID);
        } catch (SecureStore.SecureStoreException e) {
            throw new NativeBridge.BridgeException(e.code, e.getMessage(), null);
        }
    }

