    /**
     * Starts the daemon inside Termux via RUN_COMMAND. Requires: Termux installed, allow-external-apps=true in
     * ~/.termux/termux.properties, the RUN_COMMAND permission granted to this app, and ~/.opencode-si/ocd.py
     * installed (daemon/termux-setup.sh). UNVERIFIED ON A DEVICE: extra names follow the Termux RUN_COMMAND docs.
     */
    public void startDaemon() throws NativeBridge.BridgeException {
        if (!termuxInstalled()) {
            throw new NativeBridge.BridgeException("BACKEND_UNAVAILABLE", "Termux is not installed.", "package com.termux not found");
        }
        if (!hasRunCommandPermission()) {
            throw new NativeBridge.BridgeException("PERMISSION_DENIED", "This app has not been allowed to run commands in Termux.", "missing " + PERM_RUN_COMMAND);
        }
        String script = "[ -f \"$HOME/" + DAEMON_REL + "\" ] || { echo 'ocd.py is not installed. Run daemon/termux-setup.sh first.' >&2; exit 127; }\n"
                + "mkdir -p \"$HOME/" + WORKSPACE_REL + "\"\n"
                + "printf '%s\\n' \"$1\" | exec python \"$HOME/" + DAEMON_REL + "\" --token-stdin --port \"$2\" --workspace \"$HOME/" + WORKSPACE_REL + "\"\n";
        Intent i = new Intent("com.termux.RUN_COMMAND");
        i.setClassName(TERMUX_PKG, "com.termux.app.RunCommandService");
        i.putExtra("com.termux.RUN_COMMAND_PATH", TERMUX_BIN + "/bash");
        i.putExtra("com.termux.RUN_COMMAND_ARGUMENTS", new String[]{"-c", script, "opencode-si", token(), String.valueOf(port())});
        i.putExtra("com.termux.RUN_COMMAND_WORKDIR", TERMUX_HOME);
        i.putExtra("com.termux.RUN_COMMAND_BACKGROUND", true);
        try {
            if (Build.VERSION.SDK_INT >= 26) {
                ctx.startForegroundService(i);
            } else {
                ctx.startService(i);
            }
        } catch (SecurityException e) {
            throw new NativeBridge.BridgeException("PERMISSION_DENIED", "Termux refused the request. Set allow-external-apps=true in ~/.termux/termux.properties and restart Termux.", e.getClass().getSimpleName());
        } catch (RuntimeException e) {
            throw new NativeBridge.BridgeException("BACKEND_ERROR", "Could not start Termux.", e.getClass().getSimpleName());
        }
    }

    // ------------------------------------------------------------------ generic Termux script runner (OpenCode lifecycle)
    private static final AtomicInteger RESULT_SEQ = new AtomicInteger();

    /**
     * Runs a bash script in Termux in BACKGROUND mode (no terminal window opens) and waits up to timeoutMs for Termux's
     * result (stdout, stderr, exit code) which Termux returns through a PendingIntent. Arguments are passed positionally
     * ($1, $2, ...) and never spliced into the script text.
     *
     * Throws PERMISSION_DENIED if Android or Termux refuses the request (RUN_COMMAND not granted, or allow-external-apps
     * is not true). Returns delivered=false when the request was accepted but Termux sent no result in time: that is
     * "unknown", not "failed" and not "succeeded", and callers must verify by probing the server itself.
     * UNVERIFIED ON A DEVICE: the extra names and the result bundle keys follow the Termux RUN_COMMAND documentation.
     */
    public OpenCodeServer.ScriptResult runScript(String script, String[] args, long timeoutMs) throws NativeBridge.BridgeException {
        if (!termuxInstalled()) {
            throw new NativeBridge.BridgeException("BACKEND_UNAVAILABLE", "Termux is not installed.", "package com.termux not found");
        }
        if (!hasRunCommandPermission()) {
            throw new NativeBridge.BridgeException("PERMISSION_DENIED", "This app has not been allowed to run commands in Termux.", "missing " + PERM_RUN_COMMAND);
        }
        final String action = ctx.getPackageName() + ".TERMUX_RESULT." + RESULT_SEQ.incrementAndGet() + "." + Long.toHexString(System.nanoTime());
        final CountDownLatch done = new CountDownLatch(1);
        final AtomicReference<Bundle> got = new AtomicReference<Bundle>();
        BroadcastReceiver rx = new BroadcastReceiver() {
            @Override
            public void onReceive(Context c, Intent i) {
                got.set(i.getBundleExtra("result"));
                done.countDown();
            }
        };
        IntentFilter filter = new IntentFilter(action);
        if (Build.VERSION.SDK_INT >= 33) {
            ctx.registerReceiver(rx, filter, Context.RECEIVER_NOT_EXPORTED);
        } else {
            ctx.registerReceiver(rx, filter);
        }
        try {
            int flags = PendingIntent.FLAG_UPDATE_CURRENT | (Build.VERSION.SDK_INT >= 31 ? PendingIntent.FLAG_MUTABLE : 0);
            PendingIntent pi = PendingIntent.getBroadcast(ctx, RESULT_SEQ.get(), new Intent(action).setPackage(ctx.getPackageName()), flags);
            String[] argv = new String[3 + (args == null ? 0 : args.length)];
            argv[0] = "-c";
            argv[1] = script;
            argv[2] = "opencode-si";
            for (int k = 0; args != null && k < args.length; k++) {
                argv[3 + k] = args[k] == null ? "" : args[k];
            }
            Intent i = new Intent("com.termux.RUN_COMMAND");
            i.setClassName(TERMUX_PKG, "com.termux.app.RunCommandService");
            i.putExtra("com.termux.RUN_COMMAND_PATH", TERMUX_BIN + "/bash");
            i.putExtra("com.termux.RUN_COMMAND_ARGUMENTS", argv);
            i.putExtra("com.termux.RUN_COMMAND_WORKDIR", TERMUX_HOME);
            i.putExtra("com.termux.RUN_COMMAND_BACKGROUND", true);
            i.putExtra("com.termux.RUN_COMMAND_PENDING_INTENT", pi);
            try {
                if (Build.VERSION.SDK_INT >= 26) {
                    ctx.startForegroundService(i);
                } else {
                    ctx.startService(i);
                }
            } catch (SecurityException e) {
                throw new NativeBridge.BridgeException("PERMISSION_DENIED",
                        "Termux refused the request. Set allow-external-apps=true in ~/.termux/termux.properties, then fully restart Termux.", e.getClass().getSimpleName());
            } catch (RuntimeException e) {
                throw new NativeBridge.BridgeException("BACKEND_ERROR", "Android did not let this app contact Termux (background start restriction?). Open Termux once and try again.", e.getClass().getSimpleName());
            }
            boolean arrived;
            try {
                arrived = done.await(Math.max(1000, timeoutMs), TimeUnit.MILLISECONDS);
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
                arrived = false;
            }
            Bundle b = got.get();
            if (!arrived || b == null) {
                return new OpenCodeServer.ScriptResult(false, -1, "", "", "no result from Termux within " + (timeoutMs / 1000) + " s");
            }
            int err = b.getInt("err", -1);
            String errmsg = b.getString("errmsg", null);
            int exit = b.getInt("exitCode", err > 0 ? err : 0);
            if (err > 0 && errmsg != null && errmsg.length() > 0) {
                return new OpenCodeServer.ScriptResult(true, exit == 0 ? 1 : exit, b.getString("stdout", ""), b.getString("stderr", ""), errmsg);
            }
            return new OpenCodeServer.ScriptResult(true, exit, b.getString("stdout", ""), b.getString("stderr", ""), null);
        } finally {
            try {
                ctx.unregisterReceiver(rx);
            } catch (RuntimeException ignored) {
            }
        }
    }

