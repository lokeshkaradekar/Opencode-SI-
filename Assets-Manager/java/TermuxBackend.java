    // ------------------------------------------------------------------ terminal (persistent PTY)
    /** Returns the project's PTY session id, creating or re-creating it when needed. */
    public String ensureSession(String project) throws NativeBridge.BridgeException {
        String sid = sessions.get(project);
        if (sid != null) {
            try {
                call("GET", "/v1/sessions/" + sid, null, 8000);
                return sid;
            } catch (NativeBridge.BridgeException e) {
                if (!"NOT_FOUND".equals(e.code)) {
                    throw e;
                }
                sessions.remove(project);
            }
        }
        JSONObject b = json("project", project);
        JSONObject info = data(post("/v1/sessions", b));
        sid = info.optString("id");
        sessions.put(project, sid);
        return sid;
    }

    /**
     * Runs one command in the project's persistent shell and blocks until it ends (SUCCESS, FAILED, CANCELLED or
     * TIMEOUT). Output is streamed to the listener while it runs. A PTY merges stdout and stderr, so everything is
     * returned in "stdout" and "stderr" is empty (see docs/DAEMON.md).
     */
    public JSONObject exec(String project, String command, boolean confirmed, long timeoutMs, StreamListener listener) throws NativeBridge.BridgeException {
        String sid = ensureSession(project);
        JSONObject b = json("command", command);
        try {
            b.put("confirmed", confirmed);
            b.put("timeout_ms", timeoutMs);
            b.put("source", "user");
        } catch (Exception ignored) {
        }
        JSONObject started = data(post("/v1/sessions/" + sid + "/exec", b));
        String cmdId = String.valueOf(started.optInt("id"));
        long since = started.optLong("seq", 0);
        running.put(project, sid);
        StringBuilder out = new StringBuilder();
        try {
            int failures = 0;
            while (!closed) {
                JSONObject r;
                try {
                    r = data(call("GET", "/v1/sessions/" + sid + "/events?since=" + since + "&wait_ms=20000", null, 35000));
                    failures = 0;
                } catch (NativeBridge.BridgeException e) {
                    if (++failures >= 3 || "NOT_FOUND".equals(e.code)) {
                        throw e;
                    }
                    continue;
                }
                since = r.optLong("next", since);
                JSONArray evs = r.optJSONArray("events");
                for (int i = 0; evs != null && i < evs.length(); i++) {
                    JSONObject ev = evs.optJSONObject(i);
                    if (ev == null || !cmdId.equals(String.valueOf(ev.opt("cmd")))) {
                        continue;
                    }
                    String type = ev.optString("type");
                    if ("output".equals(type)) {
                        String chunk = ev.optString("data", "");
                        if (out.length() < 4 * 1024 * 1024) {
                            out.append(chunk);
                        }
                        if (listener != null && chunk.length() > 0) {
                            listener.onOutput(project, cmdId, chunk);
                        }
                    } else if ("command_end".equals(type)) {
                        try {
                            return new JSONObject().put("stdout", out.toString()).put("stderr", "")
                                    .put("exitCode", ev.isNull("exit_code") ? -1 : ev.optInt("exit_code", -1))
                                    .put("status", ev.optString("status", "FAILED"))
                                    .put("cwd", ev.optString("cwd", ""))
                                    .put("durationMs", ev.optLong("duration_ms", 0))
                                    .put("commandId", cmdId);
                        } catch (Exception e) {
                            throw new NativeBridge.BridgeException("INTERNAL", "Could not read the command result.", null);
                        }
                    } else if ("session_exit".equals(type)) {
                        throw new NativeBridge.BridgeException("SHELL_EXITED", "The shell ended while the command was running.", null);
                    }
                }
            }
            throw new NativeBridge.BridgeException("BACKEND_CLOSED", "The app is shutting down.", null);
        } finally {
            running.remove(project);
        }
    }

    public boolean isRunning(String project) {
        return running.containsKey(project);
    }

    /** Cancel with escalation (SIGINT -> SIGTERM -> SIGKILL) done by the daemon; final state is CANCELLED. */
    public JSONObject cancel(String project) throws NativeBridge.BridgeException {
        String sid = sessions.get(project);
        if (sid == null) {
            throw new NativeBridge.BridgeException("NOT_RUNNING", "No terminal session is open for this project.", null);
        }
        return data(post("/v1/sessions/" + sid + "/cancel", new JSONObject()));
    }

    /** Sends the real Ctrl+C key (ETX) through the tty. */
    public JSONObject interrupt(String project) throws NativeBridge.BridgeException {
        String sid = sessions.get(project);
        if (sid == null) {
            throw new NativeBridge.BridgeException("NOT_RUNNING", "No terminal session is open for this project.", null);
        }
        return data(post("/v1/sessions/" + sid + "/interrupt", new JSONObject()));
    }

    public JSONObject stdin(String project, String text) throws NativeBridge.BridgeException {
        String sid = sessions.get(project);
        if (sid == null) {
            throw new NativeBridge.BridgeException("NOT_RUNNING", "No terminal session is open for this project.", null);
        }
        return data(post("/v1/sessions/" + sid + "/stdin", json("data", text)));
    }

    public JSONObject resize(String project, int cols, int rows) throws NativeBridge.BridgeException {
        String sid = sessions.get(project);
        if (sid == null) {
            return new JSONObject();
        }
        JSONObject b = new JSONObject();
        try {
            b.put("cols", Math.max(10, Math.min(500, cols)));
            b.put("rows", Math.max(2, Math.min(300, rows)));
        } catch (Exception ignored) {
        }
        return data(post("/v1/sessions/" + sid + "/resize", b));
    }

    public JSONObject restartSession(String project) throws NativeBridge.BridgeException {
        String sid = ensureSession(project);
        return data(post("/v1/sessions/" + sid + "/restart", new JSONObject()));
    }

    public JSONObject sessionInfo(String project) throws NativeBridge.BridgeException {
        String sid = sessions.get(project);
        if (sid == null) {
            return null;
        }
        return data(call("GET", "/v1/sessions/" + sid, null, 8000));
    }

    public void forgetProject(String project) {
        sessions.remove(project);
        running.remove(project);
    }

    // ------------------------------------------------------------------ helpers
    static JSONObject json(String k, Object v) {
        JSONObject o = new JSONObject();
        try {
            o.put(k, v);
        } catch (Exception ignored) {
        }
        return o;
    }

    /** Called when the activity is destroyed. Does not stop the daemon: it may serve other work and survives the UI. */
