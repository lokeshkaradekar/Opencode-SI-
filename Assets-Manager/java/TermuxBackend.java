    // ------------------------------------------------------------------ HTTP
    /** Performs one call and returns the full envelope. Throws BridgeException for transport errors and for success=false. */
    public JSONObject call(String method, String path, JSONObject body, int timeoutMs) throws NativeBridge.BridgeException {
        if (closed) {
            throw new NativeBridge.BridgeException("BACKEND_CLOSED", "The app is shutting down.", null);
        }
        String tok = token();
        HttpURLConnection c = null;
        try {
            URL url = new URL("http", "127.0.0.1", port(), path);
            c = (HttpURLConnection) url.openConnection(Proxy.NO_PROXY);       // never through a proxy
            c.setInstanceFollowRedirects(false);
            c.setConnectTimeout(3000);
            c.setReadTimeout(timeoutMs);
            c.setRequestMethod(method);
            c.setRequestProperty("Authorization", "Bearer " + tok);
            c.setRequestProperty("Accept", "application/json");
            if (body != null) {
                byte[] bytes = body.toString().getBytes(UTF8);
                c.setDoOutput(true);
                c.setRequestProperty("Content-Type", "application/json");
                c.setFixedLengthStreamingMode(bytes.length);
                OutputStream os = c.getOutputStream();
                try {
                    os.write(bytes);
                } finally {
                    os.close();
                }
            }
            int status = c.getResponseCode();
            InputStream in = status >= 400 ? c.getErrorStream() : c.getInputStream();
            String text = in == null ? "" : readAll(in);
            JSONObject env;
            try {
                env = new JSONObject(text);
            } catch (Exception e) {
                throw new NativeBridge.BridgeException("DAEMON_BAD_RESPONSE", "The daemon sent an unreadable answer (HTTP " + status + ").", null);
            }
            if (!env.optBoolean("success", false)) {
                JSONObject err = env.optJSONObject("error");
                String code = err == null ? "DAEMON_ERROR" : err.optString("code", "DAEMON_ERROR");
                String msg = err == null ? "The daemon reported an error." : err.optString("message", "The daemon reported an error.");
                Object det = err == null ? null : err.opt("details");
                if (status == 401 || "UNAUTHORIZED".equals(code)) {
                    throw new NativeBridge.BridgeException("DAEMON_AUTH_FAILED",
                            "The daemon rejected this app's token. If you started the daemon yourself, stop it (pkill -f ocd.py) so the app can start it, or enter its token in Settings.", null);
                }
                String d = det == null || det == JSONObject.NULL ? null : det.toString();
                if (d != null && d.length() > 2000) {
                    d = d.substring(0, 2000);
                }
                throw new NativeBridge.BridgeException(code, msg, d);
            }
            return env;
        } catch (NativeBridge.BridgeException e) {
            throw e;
        } catch (ConnectException e) {
            throw new NativeBridge.BridgeException("DAEMON_UNREACHABLE", "The Termux daemon is not running on port " + port() + ".", "connection refused");
        } catch (SocketTimeoutException e) {
            throw new NativeBridge.BridgeException("DAEMON_TIMEOUT", "The daemon did not answer in time.", null);
        } catch (IOException e) {
            throw new NativeBridge.BridgeException("DAEMON_UNREACHABLE", "Could not talk to the Termux daemon.", e.getClass().getSimpleName());
        } finally {
            if (c != null) {
                c.disconnect();
            }
        }
    }

    private static String readAll(InputStream in) throws IOException {
        try {
            ByteArrayOutputStream bos = new ByteArrayOutputStream();
            byte[] buf = new byte[16384];
            int n;
            while ((n = in.read(buf)) > 0) {
                bos.write(buf, 0, n);
                if (bos.size() > MAX_RESPONSE) {
                    throw new IOException("response too large");
                }
            }
            return new String(bos.toByteArray(), UTF8);
        } finally {
            in.close();
        }
    }

    /** Envelope -> data object (daemon data is an object for every call except list endpoints; see dataArray). */
    static JSONObject data(JSONObject env) {
        JSONObject d = env.optJSONObject("data");
        return d == null ? new JSONObject() : d;
    }

    static JSONArray dataArray(JSONObject env) {
        JSONArray a = env.optJSONArray("data");
        return a == null ? new JSONArray() : a;
    }

